import shutil
from pathlib import Path

import dagster as dg
from schemas.validation import MIN_GRIB_SIZE_BYTES, is_valid_grib_file


class RawFileIOManager(dg.ConfigurableIOManager):
    base_path: str = ""
    min_size_bytes: int = MIN_GRIB_SIZE_BYTES

    def _resolve_target_path(
        self,
        asset_key: dg.AssetKey,
        partition_key: str | None = None,
    ) -> Path:
        dir_path = Path(self.base_path).joinpath(*asset_key.path)
        if partition_key is not None:
            year = (
                partition_key[:4]
                if len(partition_key) >= 4 and partition_key[:4].isdigit()
                else "unknown"
            )
            return dir_path / year / f"{partition_key}.grib"
        return dir_path / "data.grib"

    def _get_path(self, context: dg.OutputContext | dg.InputContext) -> Path:
        """Construct the storage path based on the asset key and partition."""
        partition_key = context.partition_key if context.has_partition_key else None
        return self._resolve_target_path(context.asset_key, partition_key)

    def existing_partition(
        self,
        asset_key: dg.AssetKey,
        partition_key: str | None = None,
    ) -> Path | None:
        """Return the L0 file path if a valid GRIB file already exists for the partition."""
        target_path = self._resolve_target_path(asset_key, partition_key)
        if is_valid_grib_file(target_path, min_size_bytes=self.min_size_bytes):
            return target_path
        return None

    def handle_output(self, context: dg.OutputContext, obj: Path | str) -> None:
        """Move the temporary file generated by the asset to the final L0 storage location."""
        if not isinstance(obj, (Path, str)):
            raise dg.DagsterInvariantViolationError(
                f"RawFileIOManager expects a file path (Path or str), got {type(obj)}"
            )

        source_path = Path(obj)
        if not source_path.exists():
            raise FileNotFoundError(f"Source file does not exist: {source_path}")

        if not is_valid_grib_file(source_path, min_size_bytes=self.min_size_bytes):
            source_path.unlink(missing_ok=True)
            raise dg.DagsterInvariantViolationError(
                f"Source file {source_path} is not a valid GRIB file "
                f"(must start with b'GRIB' and be >= {self.min_size_bytes} bytes)."
            )

        target_path = self._get_path(context)
        target_path.parent.mkdir(parents=True, exist_ok=True)

        if source_path.resolve() != target_path.resolve():
            context.log.info(f"Moving L0 data from {source_path} to {target_path}")
            shutil.move(source_path, target_path)

        size_bytes = target_path.stat().st_size
        context.add_output_metadata(
            {
                "storage_path": dg.MetadataValue.path(str(target_path)),
                "size_bytes": dg.MetadataValue.int(size_bytes),
                "size_human_readable": dg.MetadataValue.text(
                    f"{size_bytes / (1024 * 1024):.2f} MB"
                ),
            }
        )

    def load_input(self, context: dg.InputContext) -> Path:
        """Return the path to the stored L0 file for the downstream asset to read."""
        target_path = self._get_path(context)

        if not target_path.exists():
            raise FileNotFoundError(f"Required L0 input file not found: {target_path}")

        context.log.info(f"Loading L0 data from {target_path}")
        return target_path
